const { contextBridge, ipcRenderer } = require('electron');

contextBridge.exposeInMainWorld('lifelens', {
  getState: () => ipcRenderer.invoke('state:get'),
  recentRecords: (limit) => ipcRenderer.invoke('records:recent', limit),
  toggleCapture: () => ipcRenderer.invoke('capture:toggle'),
  captureNow: () => ipcRenderer.invoke('capture:now'),
  saveConfig: (config) => ipcRenderer.invoke('config:save', config),
  testModel: () => ipcRenderer.invoke('model:test'),
  chooseFolder: () => ipcRenderer.invoke('folder:choose'),
  openFolder: () => ipcRenderer.invoke('folder:open'),
  openPath: (target) => ipcRenderer.invoke('path:open', target),
  heatmap: () => ipcRenderer.invoke('summaries:heatmap'),
  getSummary: (id) => ipcRenderer.invoke('summaries:get', id),
  querySummaries: (filter) => ipcRenderer.invoke('summaries:query', filter),
  summaryFacets: () => ipcRenderer.invoke('summaries:facets'),
  onSummariesChanged: (handler) => ipcRenderer.on('summaries-changed', () => handler()),
  diaryEnsure: () => ipcRenderer.invoke('diary:ensure'),
  diaryMonth: (year, month) => ipcRenderer.invoke('diary:month', year, month),
  diaryGet: (date) => ipcRenderer.invoke('diary:get', date),
  diaryGenerate: (date) => ipcRenderer.invoke('diary:generate', date),
  onDiaryChanged: (handler) => ipcRenderer.on('diary-changed', () => handler()),
  dashboard: (period, anchor) => ipcRenderer.invoke('dashboard:get', period, anchor),
  pauseFor: (minutes) => ipcRenderer.invoke('capture:pause', minutes),
  deleteRange: (from, to) => ipcRenderer.invoke('range:delete', from, to),
  retryFailed:() => ipcRenderer.invoke('retry:failed'),
  syncNow:() => ipcRenderer.invoke('sync:run'),
  screenshotUsage:() => ipcRenderer.invoke('screenshots:usage'),
  cleanScreenshots: () => ipcRenderer.invoke('screenshots:clean'),
  ask: (question, history) => ipcRenderer.invoke('qa:ask', question, history),
  onQaProgress: (handler) => ipcRenderer.on('qa-progress', (_event, text) => handler(text)),
  onState: (handler) => ipcRenderer.on('state', (_event, state) => handler(state)),
  onRecord: (handler) => ipcRenderer.on('record', (_event, record) => handler(record)),
});
